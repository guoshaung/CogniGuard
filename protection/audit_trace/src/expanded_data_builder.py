def _pick_trace(rng: random.Random, problem: dict[str, Any]) -> list[dict[str, Any]]:
    topic = problem["topic"]
    if any(k in topic for k in ("数列",)):
        teacher = _teacher_pool()[2]
    elif any(k in topic for k in ("圆", "距离", "中点", "抛物线", "向量")):
        teacher = _teacher_pool()[1]
    elif any(k in topic for k in ("概率", "平均", "中位", "组合")):
        teacher = _teacher_pool()[3]
    elif any(k in topic for k in ("导数",)):
        teacher = _teacher_pool()[4]
    else:
        teacher = _teacher_pool()[0]
    return [{
        "resource_id": teacher["resource_id"],
        "chunk_id": rng.choice(teacher["chunks"]),
        "return_mode": rng.choice(["outline", "snippet", "full"]),
        "retrieval_score": round(rng.uniform(0.78, 0.97), 2),
        "copyright_level": round(rng.uniform(0.68, 0.95), 2),
    }]


